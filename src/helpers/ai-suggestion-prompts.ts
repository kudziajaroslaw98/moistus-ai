export function getSuggestionSystemPrompt(
	mode: SuggestionPromptMode
): string {
	return [
		SUGGESTION_BASE_PROMPT,
		mode === 'full-map'
			? WHOLE_MAP_SUGGESTION_PROMPT
			: FOCUSED_NODE_SUGGESTION_PROMPT,
	].join('\n\n');
}
